export const formatCOP = (value) => new Intl.NumberFormat('es-CO', {
  style: 'currency',
  currency: 'COP',
  maximumFractionDigits: 0,
}).format(value);

export const formatCinemaDate = (date) => new Intl.DateTimeFormat('es-CO', {
  weekday: 'short', day: 'numeric', month: 'short', timeZone: CINEMA_VENUE.timezone,
}).format(new Date(date));

export const formatCinemaTime = (date) => new Intl.DateTimeFormat('es-CO', {
  hour: 'numeric', minute: '2-digit', hour12: true, timeZone: CINEMA_VENUE.timezone,
}).format(new Date(date));
